def module(module_id):
    return ONBOARDING[module_id]


def lesson(module_id, index):
    return ONBOARDING[module_id]["lessons"][int(index)]


def lesson_count(module_id):
    return len(ONBOARDING[module_id]["lessons"])


def route():
    """Return the compulsory entry route in display order."""
    result = []
    for module_id in MODULE_ORDER:
        for index, item in enumerate(ONBOARDING[module_id]["lessons"]):
            result.append({
                "module_id": module_id,
                "module_title": ONBOARDING[module_id]["title"],
                "index": index,
                **item,
            })
    return result


def total_lessons():
    return sum(lesson_count(module_id) for module_id in MODULE_ORDER)


def total_minutes():
    return sum(int(item.get("minutes", 0)) for item in route())


def next_position(module_id=None, lesson_index=None):
    """Return the next route item; None means onboarding is complete."""
    items = route()
    if module_id is None or lesson_index is None:
        return items[0] if items else None
    for pos, item in enumerate(items):
        if item["module_id"] == module_id and item["index"] == int(lesson_index):
            return items[pos + 1] if pos + 1 < len(items) else None
    return items[0] if items else None
