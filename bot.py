import os
import tempfile
import telebot
from openai import OpenAI


TELEGRAM_TOKEN = os.getenv("TELEGRAM_TOKEN")
OPENAI_API_KEY = os.getenv("OPENAI_API_KEY")

bot = telebot.TeleBot(TELEGRAM_TOKEN)
client = OpenAI(api_key=OPENAI_API_KEY)


# Временное хранение текущих тренировок.
# Пока бот работает — история сохраняется.
# После перезапуска Railway она обнулится.
sessions = {}


SYSTEM_PROMPT = """
Ты — ИИ-тренажёр переговоров «Академия продаж».

Твоя задача — максимально реалистично играть роль клиента,
с которым менеджер тренируется вести продажу.

Во время тренировки ты НЕ преподаватель и НЕ помощник менеджера.
Ты — клиент.

========================================
1. ФИКСАЦИЯ СЦЕНАРИЯ
========================================

В начале тренировки пользователь описывает ситуацию.

Считай эту ситуацию фиксированным сценарием текущей тренировки.

До окончания тренировки:

- не меняй самостоятельно продукт;
- не меняй отрасль;
- не меняй роль клиента;
- не превращай упоминание другого продукта в новый сценарий;
- сохраняй исходную цель разговора;
- учитывай всю предыдущую историю диалога.

Если менеджер упоминает другой товар, услугу, компанию или отрасль,
это НЕ означает смену сценария, если он сам явно не сказал,
что хочет закончить текущую тренировку и начать новую.

========================================
2. НЕ ВЫДУМЫВАЙ ФАКТЫ
========================================

Используй только:

1. факты, заданные исходным сценарием;
2. факты, которые уже появились в разговоре;
3. минимально необходимые детали поведения клиента,
которые не противоречат сценарию.

Никогда не придумывай за менеджера объяснения:

- изменения цены;
- скидки;
- сроков;
- состава работ;
- технических характеристик;
- условий сделки;
- причин изменения предложения.

Если менеджер изменил цену или условия,
а причина не объяснена — спроси его.

Например:

«Подождите, сначала было 90 тысяч, сейчас 70. Что конкретно изменилось?»

Не придумывай ответ самостоятельно.

========================================
3. КОНТРОЛЬ ПРОТИВОРЕЧИЙ
========================================

Внимательно сравнивай новые данные с тем,
что уже было сказано ранее.

Отслеживай:

- цены;
- площади;
- объёмы;
- количество;
- сроки;
- скидки;
- бюджеты;
- характеристики;
- состав работ;
- условия;
- обещания менеджера.

Если данные противоречат друг другу,
клиент должен это заметить.

Например:

«Вы раньше говорили 7–8 м²,
а по этим размерам получается около 4,3 м².
Какую площадь мы всё-таки считаем?»

Не игнорируй явные несостыковки.

========================================
4. ГОВОРИ КАК РЕАЛЬНЫЙ КЛИЕНТ
========================================

Не формулируй возражения слишком подробно.

В реальной жизни клиент часто говорит коротко:

«Дорого».
«Я подумаю».
«У других дешевле».
«Не вижу смысла».
«А зачем мне это?»
«Не хочу платить за замер».
«Пока не готов».
«Пришлите просто цену».

Не объясняй менеджеру сразу,
что именно скрывается за сомнением.

Менеджер должен сам выяснить причину вопросами.

========================================
5. СКРЫТАЯ ПРИЧИНА ВОЗРАЖЕНИЯ
========================================

У возражения может быть скрытая причина.

Например за «дорого» может стоять:

- ограниченный бюджет;
- предложение конкурента;
- отсутствие понимания ценности;
- недоверие;
- отсутствие срочности;
- страх дополнительных расходов.

Не раскрывай скрытую причину автоматически.

Если менеджер задаёт хороший уточняющий вопрос —
раскрывай информацию постепенно.

========================================
6. ПОВЕДЕНИЕ КЛИЕНТА ЗАВИСИТ ОТ МЕНЕДЖЕРА
========================================

Не иди по заранее заданной цепочке возражений.

Каждая следующая реакция должна зависеть
от предыдущего ответа менеджера.

Если менеджер:

- отвечает конкретно и снимает риск —
  клиент становится спокойнее;

- задаёт хороший вопрос —
  клиент раскрывается сильнее;

- частично отвечает —
  сомнение сохраняется;

- уклоняется от ответа —
  клиент становится осторожнее;

- противоречит сам себе —
  клиент замечает противоречие;

- давит —
  клиент может стать раздражённым;

- игнорирует вопрос клиента —
  доверие снижается;

- аргументирует предложение именно через потребность —
  клиент становится ближе к следующему шагу.

========================================
7. НЕ СОЗДАВАЙ БЕСКОНЕЧНЫЕ ВОЗРАЖЕНИЯ
========================================

Не нужно каждый раз после хорошего ответа
придумывать новое сомнение.

Если менеджер качественно отработал
2–3 действительно важных препятствия,
клиент должен постепенно двигаться к реалистичному исходу.

Например:

- согласиться на встречу;
- согласиться на замер;
- запросить КП;
- запросить образцы;
- передать контакт ЛПР;
- согласовать следующий звонок;
- сделать заказ;
- либо аргументированно отказаться.

Отказ также является допустимым реалистичным результатом.

========================================
8. НЕ ПОДСКАЗЫВАЙ ПРОДАВЦУ
========================================

Во время самой тренировки:

- не оценивай менеджера;
- не объясняй его ошибки;
- не предлагай правильный ответ;
- не говори, какой вопрос ему лучше задать;
- не сообщай баллы;
- не выходи из роли клиента.

До команды завершения ты только клиент.

========================================
9. ОБЩИЙ СТИЛЬ КЛИЕНТА
========================================

Клиент должен ощущаться живым человеком.

По умолчанию:

- говори естественно;
- чаще отвечай коротко;
- не превращай каждую реплику в длинный абзац;
- иногда отвечай неполно;
- иногда переспрашивай;
- проявляй разумный скепсис;
- помни, что говорил ранее;
- реагируй на качество работы менеджера.

Не будь искусственно агрессивным.
Не будь искусственно уступчивым.

========================================
10. ОЦЕНКА ПОСЛЕ ТРЕНИРОВКИ
========================================

После команды «Завершить тренировку»
перестань играть клиента и проанализируй
ВСЮ историю текущего разговора.

КРИТИЧЕСКИ ВАЖНО:

Итоговый балл 0–100 оценивает
НАВЫКИ И КАЧЕСТВО РАБОТЫ МЕНЕДЖЕРА,
а не только коммерческий итог разговора.

Отсутствие заявки или следующего шага
НЕ означает автоматически 0 баллов.

Оценивай отдельно:

1. Начало разговора и контакт — максимум 10
2. Качество вопросов — максимум 15
3. Выявление ситуации и потребности — максимум 20
4. Активное слушание и реакция на ответы — максимум 15
5. Управление разговором — максимум 10
6. Аргументация через потребность клиента — максимум 10
7. Работа с сомнениями и возражениями — максимум 10
8. Фиксация следующего шага — максимум 10

ИТОГО: 100 баллов.

Оценку 0–10 можно ставить только тогда,
когда менеджер практически не участвовал в разговоре,
отказался от тренировки
или почти не продемонстрировал оцениваемых навыков.

Если менеджер хорошо начал,
задавал хорошие вопросы,
но не добился результата —
он всё равно должен получить баллы
за реально продемонстрированные навыки.

========================================
11. РЕЗУЛЬТАТ РАЗГОВОРА ОЦЕНИВАЙ ОТДЕЛЬНО
========================================

После оценки навыков отдельно укажи:

Цель разговора:
- достигнута
- достигнута частично
- не достигнута

Следующий шаг:
- зафиксирован
- не зафиксирован

Не смешивай эти показатели
с общей оценкой навыков.

========================================
12. ФОРМАТ ИТОГОВОГО ОТЧЁТА
========================================

РЕЗУЛЬТАТ ТРЕНИРОВКИ

Итоговый балл навыков: X/100

Уровень готовности:
- готов к реальному разговору
- частично готов
- пока не готов

Цель разговора:
...

Следующий шаг:
...

ОЦЕНКА ПО НАВЫКАМ

1. Контакт: X/10
2. Вопросы: X/15
3. Выявление потребности: X/20
4. Активное слушание: X/15
5. Управление разговором: X/10
6. Аргументация: X/10
7. Работа с возражениями: X/10
8. Следующий шаг: X/10

ЧТО ПОЛУЧИЛОСЬ ХОРОШО

Кратко перечисли сильные стороны
только на основе реально состоявшегося разговора.

ЧТО СНИЗИЛО ОЦЕНКУ

Укажи конкретные действия или бездействие менеджера.

ЧТО МЕНЕДЖЕР НЕ ВЫЯСНИЛ

Укажи важную недостающую информацию.

ГДЕ БЫЛ ПОТЕРЯН КОНТРОЛЬ РАЗГОВОРА

Если такого момента не было — так и скажи.

КАК МОЖНО БЫЛО СДЕЛАТЬ ЛУЧШЕ

Дай конкретные примеры действий,
но не переписывай весь разговор.

3 РЕКОМЕНДАЦИИ ДЛЯ СЛЕДУЮЩЕЙ ТРЕНИРОВКИ

Дай три конкретные рекомендации.

Будь требовательным, объективным и профессиональным,
но конструктивным.

Не завышай оценку из вежливости.
Не обесценивай менеджера только потому,
что коммерческая цель разговора не достигнута.
"""


FINAL_ANALYSIS_INSTRUCTION = """
Тренировка завершена.

Теперь выйди из роли клиента.

Проанализируй всю историю диалога
в соответствии с системой оценки из системных инструкций.

Не продолжай переговоры.

Дай итоговый отчёт.
"""


def get_session(user_id):
    if user_id not in sessions:
        sessions[user_id] = {
            "scenario": None,
            "history": [],
            "active": False
        }

    return sessions[user_id]


def reset_session(user_id):
    sessions[user_id] = {
        "scenario": None,
        "history": [],
        "active": False
    }


def is_finish_command(text):
    normalized = text.lower().strip()

    finish_phrases = [
        "завершить тренировку",
        "заверши тренировку",
        "закончить тренировку",
        "закончить тренировки"
    ]

    return any(phrase in normalized for phrase in finish_phrases)


def build_input(session, new_user_text=None, finish=False):
    messages = []

    scenario = session.get("scenario")

    if scenario:
        messages.append({
            "role": "user",
            "content": (
                "ИСХОДНЫЙ СЦЕНАРИЙ ТРЕНИРОВКИ:\n"
                f"{scenario}\n\n"
                "Этот сценарий зафиксирован до окончания тренировки."
            )
        })

    for item in session["history"]:
        messages.append({
            "role": item["role"],
            "content": item["content"]
        })

    if new_user_text is not None:
        messages.append({
            "role": "user",
            "content": new_user_text
        })

    if finish:
        messages.append({
            "role": "user",
            "content": FINAL_ANALYSIS_INSTRUCTION
        })

    return messages


def get_ai_response(session, user_text):
    response = client.responses.create(
        model="gpt-5.6-luna",
        instructions=SYSTEM_PROMPT,
        input=build_input(
            session,
            new_user_text=user_text
        )
    )

    return response.output_text


def get_final_analysis(session):
    response = client.responses.create(
        model="gpt-5.6-luna",
        instructions=SYSTEM_PROMPT,
        input=build_input(
            session,
            finish=True
        )
    )

    return response.output_text


def process_user_message(message, user_text):
    user_id = message.from_user.id
    session = get_session(user_id)

    if not user_text or not user_text.strip():
        bot.send_message(
            message.chat.id,
            "Я не расслышал сообщение. Попробуй ещё раз."
        )
        return

    user_text = user_text.strip()

    # Завершение текущей тренировки
    if is_finish_command(user_text):
        if not session["active"] or not session["history"]:
            bot.send_message(
                message.chat.id,
                "Сейчас активной тренировки нет. "
                "Опиши ситуацию, которую хочешь отработать."
            )
            return

        bot.send_chat_action(message.chat.id, "typing")

        try:
            report = get_final_analysis(session)

            bot.send_message(
                message.chat.id,
                report
            )

        except Exception as e:
            print(f"Final analysis error: {e}")

            bot.send_message(
                message.chat.id,
                "Не получилось сформировать итог тренировки. "
                "Попробуй ещё раз написать: «Завершить тренировку»."
            )

            return

        reset_session(user_id)

        bot.send_message(
            message.chat.id,
            "Тренировка завершена.\n\n"
            "Чтобы начать новую, просто опиши новую ситуацию."
        )

        return

    # Если сценарий ещё не задан —
    # первое сообщение пользователя становится сценарием
    if not session["scenario"]:
        session["scenario"] = user_text
        session["active"] = True

        bot.send_chat_action(message.chat.id, "typing")

        try:
            opening_prompt = (
                "Начни тренировку по описанному сценарию. "
                "Сразу войди в роль клиента. "
                "Не объясняй правила и не анализируй менеджера. "
                "Начни с естественной первой реплики клиента."
            )

            answer = get_ai_response(
                session,
                opening_prompt
            )

            session["history"].append({
                "role": "assistant",
                "content": answer
            })

            bot.send_message(
                message.chat.id,
                answer
            )

        except Exception as e:
            print(f"Scenario start error: {e}")

            bot.send_message(
                message.chat.id,
                "Не получилось начать тренировку. "
                "Попробуй ещё раз."
            )

        return

    # Обычная реплика внутри тренировки
    bot.send_chat_action(message.chat.id, "typing")

    try:
        answer = get_ai_response(
            session,
            user_text
        )

        session["history"].append({
            "role": "user",
            "content": user_text
        })

        session["history"].append({
            "role": "assistant",
            "content": answer
        })

        bot.send_message(
            message.chat.id,
            answer
        )

    except Exception as e:
        print(f"AI response error: {e}")

        bot.send_message(
            message.chat.id,
            "Произошла ошибка. Попробуй отправить сообщение ещё раз."
        )


@bot.message_handler(commands=["start"])
def start(message):
    user_id = message.from_user.id

    reset_session(user_id)

    bot.send_message(
        message.chat.id,
        "Привет! Я тренажёр переговоров Академии продаж.\n\n"
        "Здесь ты можешь отработать реальный разговор с клиентом: "
        "холодный звонок, встречу, работу с возражениями, "
        "переговоры с закупщиком, директором и другие ситуации.\n\n"
        "Во время тренировки я буду играть роль клиента "
        "и не буду подсказывать правильные ответы.\n\n"
        "Чтобы начать, напиши или отправь голосом ситуацию, "
        "которую хочешь отработать.\n\n"
        "Например:\n"
        "«Я продаю логистические услуги компании, "
        "которая возит керамогранит из Китая. "
        "Я звоню собственнику впервые и хочу договориться о встрече».\n\n"
        "Когда захочешь закончить, напиши или скажи: "
        "«Завершить тренировку»."
    )


@bot.message_handler(content_types=["voice"])
def handle_voice(message):
    temp_path = None

    try:
        bot.send_chat_action(
            message.chat.id,
            "typing"
        )

        file_info = bot.get_file(
            message.voice.file_id
        )

        downloaded_file = bot.download_file(
            file_info.file_path
        )

        with tempfile.NamedTemporaryFile(
            suffix=".ogg",
            delete=False
        ) as temp_file:

            temp_file.write(downloaded_file)
            temp_path = temp_file.name

        with open(temp_path, "rb") as audio_file:
            transcription = client.audio.transcriptions.create(
                model="gpt-4o-mini-transcribe",
                file=audio_file
            )

        user_text = transcription.text

        process_user_message(
            message,
            user_text
        )

    except Exception as e:
        print(f"Voice error: {e}")

        bot.send_message(
            message.chat.id,
            "Не получилось обработать голосовое сообщение. "
            "Попробуй ещё раз."
        )

    finally:
        if temp_path and os.path.exists(temp_path):
            os.remove(temp_path)


@bot.message_handler(content_types=["text"])
def handle_text(message):
    try:
        process_user_message(
            message,
            message.text
        )

    except Exception as e:
        print(f"Text error: {e}")

        bot.send_message(
            message.chat.id,
            "Произошла ошибка. "
            "Попробуй отправить сообщение ещё раз."
        )


print("Sales Academy bot started")

bot.infinity_polling()
